// Bundles supabase/migrations + seed.sql + content/kb/*.md into
//   - supabase/seed_kb.sql            (run after seed.sql on a real Supabase project)
//   - lib/db/bootstrap.generated.ts   (used by the in-process PGlite demo database)
// Runs automatically before dev/build/test.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const q = (s) => (s === null || s === undefined || s === "" ? "null" : `'${String(s).replace(/'/g, "''")}'`);

function parseMd(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error("missing frontmatter");
  const meta = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    const k = line.slice(0, i).trim();
    let v = line.slice(i + 1).trim();
    if (v.startsWith("[")) v = v.slice(1, -1).split(",").map((x) => x.trim()).filter(Boolean);
    meta[k] = v;
  }
  const body = m[2].trim();
  const title = body.match(/^# (.+)$/m)?.[1] ?? meta.slug;
  return { meta, title, body: body.replace(/^# .+\n+/, "") };
}

const kbRows = [];
for (const lang of ["vi", "ja", "en"]) {
  const dir = join(root, "content", "kb", lang);
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".md")).sort()) {
    const { meta, title, body } = parseMd(readFileSync(join(dir, f), "utf8"));
    const pref = meta.prefecture === "national" ? null : meta.prefecture;
    const tags = `array[${(meta.tags || []).map(q).join(",")}]::text[]`;
    kbRows.push(
      `(${q(meta.slug)}, ${q(pref)}, ${q(meta.topic)}, ${q(lang)}, ${q(title)}, ${q(body)}, ${tags}, ${q(meta.source_url)}, ${meta.sample !== "false"})`,
    );
  }
}
const kbSql =
  `-- GENERATED by scripts/build-sql.mjs from content/kb/*.md — do not edit by hand.\n` +
  `insert into public.kb_articles (slug, prefecture_code, topic, language, title, body_md, tags, source_url, is_sample) values\n` +
  kbRows.join(",\n") +
  `\non conflict (slug, language) do update set title = excluded.title, body_md = excluded.body_md, tags = excluded.tags,\n  topic = excluded.topic, prefecture_code = excluded.prefecture_code, source_url = excluded.source_url, updated_at = now();\n`;
writeFileSync(join(root, "supabase", "seed_kb.sql"), kbSql);

const migDir = join(root, "supabase", "migrations");
const migrations = readdirSync(migDir).filter((f) => f.endsWith(".sql")).sort().map((f) => ({ name: f, sql: readFileSync(join(migDir, f), "utf8") }));
const seed = readFileSync(join(root, "supabase", "seed.sql"), "utf8");

const ts =
  `// GENERATED by scripts/build-sql.mjs — do not edit. Source: supabase/ + content/kb/.\n` +
  `export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations)};\n` +
  `export const SEED_SQL: string = ${JSON.stringify(seed)};\n` +
  `export const SEED_KB_SQL: string = ${JSON.stringify(kbSql)};\n`;
writeFileSync(join(root, "lib", "db", "bootstrap.generated.ts"), ts);
console.log(`build-sql: ${migrations.length} migrations, ${kbRows.length} KB rows`);
